#!/usr/bin/env node

import { randomUUID } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";
import * as prettier from "prettier";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const viteAppRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(viteAppRoot, "../..");

export const DEFAULT_SCHEMA_PATH = path.join(repoRoot, "backend", "openapi.json");
export const DEFAULT_OUTPUT_PATH = path.join(viteAppRoot, "src", "lib", "api.generated.ts");

const GENERATED_BANNER = `/**
 * Generated from backend/openapi.json by openapi-typescript.
 * Do not edit this file directly; run pnpm generate:api-types.
 */

`;

function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function decodePointerToken(token, reference) {
  try {
    return decodeURIComponent(token).replaceAll("~1", "/").replaceAll("~0", "~");
  } catch (error) {
    throw new Error(`Invalid percent-encoding in local $ref ${reference}`, {
      cause: error,
    });
  }
}

function resolveLocalReference(document, reference, sourcePath) {
  if (typeof reference !== "string" || !reference.startsWith("#/")) {
    throw new Error(
      `Remote or unsupported $ref at ${sourcePath}: ${String(reference)}. ` +
        "Only in-document JSON pointer references are allowed.",
    );
  }

  const tokens = reference
    .slice(2)
    .split("/")
    .map((token) => decodePointerToken(token, reference));
  let current = document;
  for (const token of tokens) {
    if (
      typeof current !== "object" ||
      current === null ||
      !Object.prototype.hasOwnProperty.call(current, token)
    ) {
      throw new Error(
        `Out-of-bounds local $ref at ${sourcePath}: ${reference} ` +
          `(missing token ${JSON.stringify(token)})`,
      );
    }
    current = current[token];
  }
}

export function assertLocalReferences(document) {
  const pending = [{ value: document, sourcePath: "$" }];
  while (pending.length > 0) {
    const { value, sourcePath } = pending.pop();
    if (Array.isArray(value)) {
      value.forEach((entry, index) => {
        pending.push({ value: entry, sourcePath: `${sourcePath}[${index}]` });
      });
      continue;
    }
    if (!isRecord(value)) continue;

    for (const [key, entry] of Object.entries(value)) {
      if (key === "$ref") {
        resolveLocalReference(document, entry, sourcePath);
      } else {
        pending.push({ value: entry, sourcePath: `${sourcePath}.${key}` });
      }
    }
  }
}

export async function loadSchema(schemaPath = DEFAULT_SCHEMA_PATH) {
  let raw;
  try {
    raw = await fs.readFile(schemaPath, "utf8");
  } catch (error) {
    throw new Error(`Cannot read OpenAPI schema: ${schemaPath}`, { cause: error });
  }

  let schema;
  try {
    schema = JSON.parse(raw);
  } catch (error) {
    throw new Error(`OpenAPI schema is not valid JSON: ${schemaPath}`, {
      cause: error,
    });
  }
  if (!isRecord(schema)) {
    throw new Error(`OpenAPI schema root must be an object: ${schemaPath}`);
  }
  if (typeof schema.openapi !== "string" || !schema.openapi.startsWith("3.1.")) {
    throw new Error(
      `Expected an OpenAPI 3.1 document at ${schemaPath}, got ${String(schema.openapi)}`,
    );
  }
  assertLocalReferences(schema);
  return schema;
}

export async function renderApiTypes({
  schemaPath = DEFAULT_SCHEMA_PATH,
  outputPath = DEFAULT_OUTPUT_PATH,
} = {}) {
  const schema = await loadSchema(schemaPath);
  const ast = await openapiTS(schema);
  const unformatted = `${GENERATED_BANNER}${astToString(ast)}`;
  const prettierConfig = (await prettier.resolveConfig(DEFAULT_OUTPUT_PATH)) ?? {};
  return prettier.format(unformatted, {
    ...prettierConfig,
    filepath: outputPath,
  });
}

async function writeAtomic(outputPath, contents) {
  const temporaryPath = path.join(
    path.dirname(outputPath),
    `.${path.basename(outputPath)}.${process.pid}.${randomUUID()}.tmp`,
  );
  try {
    await fs.writeFile(temporaryPath, contents, {
      encoding: "utf8",
      flag: "wx",
    });
    await fs.rename(temporaryPath, outputPath);
  } catch (error) {
    await fs.rm(temporaryPath, { force: true });
    throw new Error(`Cannot write generated API types: ${outputPath}`, {
      cause: error,
    });
  }
}

export async function generateApiTypes({
  schemaPath = DEFAULT_SCHEMA_PATH,
  outputPath = DEFAULT_OUTPUT_PATH,
  check = false,
} = {}) {
  const rendered = await renderApiTypes({ schemaPath, outputPath });
  if (check) {
    let current;
    try {
      current = await fs.readFile(outputPath);
    } catch (error) {
      throw new Error(`Generated API types are missing: ${outputPath}`, {
        cause: error,
      });
    }
    if (!current.equals(Buffer.from(rendered, "utf8"))) {
      throw new Error(`Generated API types are stale: ${outputPath}. Run pnpm generate:api-types.`);
    }
    return { changed: false };
  }

  await writeAtomic(outputPath, rendered);
  return { changed: true };
}

export function parseGenerateArgs(argv) {
  const options = {
    check: false,
    schemaPath: DEFAULT_SCHEMA_PATH,
    outputPath: DEFAULT_OUTPUT_PATH,
    help: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--check") {
      options.check = true;
      continue;
    }
    if (argument === "--help" || argument === "-h") {
      options.help = true;
      continue;
    }
    if (argument === "--schema" || argument === "--output") {
      const value = argv[index + 1];
      if (!value || value.startsWith("--")) {
        throw new Error(`${argument} requires a path`);
      }
      if (argument === "--schema") {
        options.schemaPath = path.resolve(value);
      } else {
        options.outputPath = path.resolve(value);
      }
      index += 1;
      continue;
    }
    throw new Error(`Unknown argument: ${argument}`);
  }

  return options;
}

export function usage() {
  return `Usage: node scripts/generate-api-types.mjs [--check]
       [--schema <openapi.json>] [--output <api.generated.ts>]

Generates TypeScript types from the tracked local OpenAPI schema. --check
compares generated bytes and never writes the output file.`;
}

async function runMain(argv = process.argv.slice(2)) {
  try {
    const options = parseGenerateArgs(argv);
    if (options.help) {
      console.log(usage());
      return 0;
    }

    const result = await generateApiTypes(options);
    if (options.check) {
      console.log(`API types are current: ${options.outputPath}`);
    } else {
      console.log(`${result.changed ? "Wrote" : "Unchanged"} API types: ${options.outputPath}`);
    }
    return 0;
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error(`API type generation failed: ${message}`);
    return 1;
  }
}

if (path.resolve(process.argv[1] ?? "") === __filename) {
  process.exitCode = await runMain();
}
