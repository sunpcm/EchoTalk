test("media config accepts formatter-style arrays while refusing escaped duplicate keys and oversized input", (t) => {
  const f = fixture(t),
    path = join(f.project, "src-tauri/media-config.json");
  writeFileSync(path, '{\n  "version": 1,\n  "api_origin": null,\n  "media_origins": []\n}\n');
  assert.doesNotThrow(() => validateInputs(f.plan));
  // Exercise the production parser with a formatted enabled array through CSP validation.
  writeFileSync(
    path,
    '{ "version": 1, "api_origin": "https://api.example.test", "media_origins": ["wss://media.example.test"] }\n',
  );
  assert.throws(() => validateInputs(f.plan), failed("CONFIG_FORBIDDEN")); // schema accepted; explicit CSP still missing.
  writeFileSync(
    path,
    String.raw`{"version":1,"ver\u0073ion":1,"api_origin":null,"media_origins":[]}`,
  );
  assert.throws(() => validateInputs(f.plan), failed("MEDIA_CONFIG_INVALID"));
  writeFileSync(path, " ".repeat(16385) + '{"version":1,"api_origin":null,"media_origins":[]}');
  assert.throws(() => validateInputs(f.plan), failed("MEDIA_CONFIG_INVALID"));
});
