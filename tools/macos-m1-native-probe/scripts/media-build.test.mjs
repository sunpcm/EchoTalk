test("configured CSP permits only explicit WSS and its same-host HTTPS, retaining exact IPC/media/script policy", (t) => {
  const f = fixture(t);
  const media = {
    version: 1,
    api_origin: "https://api.example.test",
    media_origins: ["wss://media.example.test:9443"],
  };
  writeFileSync(
    join(f.project, "src-tauri/media-config.json"),
    JSON.stringify(media, null, 2) + "\n",
  );
  const path = join(f.project, "src-tauri/tauri.conf.json"),
    c = JSON.parse(readFileSync(path));
  assert.throws(() => validateInputs(f.plan), failed("CONFIG_FORBIDDEN"));
  c.app.security.csp = c.app.security.csp.replace(
    "connect-src ipc: http://ipc.localhost",
    `connect-src ${mediaConnectSources(media).join(" ")}`,
  );
  writeFileSync(path, JSON.stringify(c));
  assert.equal(executeBuild(f.plan, runner(f)).stage, "built-not-run");
  c.app.security.csp = c.app.security.csp.replace(
    "connect-src ipc:",
    "connect-src https://evil.test ipc:",
  );
  writeFileSync(path, JSON.stringify(c));
  const r = runner(f);
  assert.throws(() => executeBuild(f.plan, r), failed("CONFIG_FORBIDDEN"));
  assert.equal(r.calls.length, 0);
});

